-- Noteboard + visitor counter for the portfolio site.
-- Run this once in your Supabase project: Dashboard → SQL Editor → New query → paste → Run.
-- Then copy the Project URL and the publishable (anon) key into NOTES_API in script.js.

-- ── STICKY NOTES ───────────────────────────────────────────
create table if not exists public.notes (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  body        text not null check (char_length(body) between 1 and 280),
  name        text check (char_length(name) <= 40),
  color       text not null default 'yellow'
              check (color in ('yellow', 'pink', 'mint', 'blue', 'peach')),
  email       text check (char_length(email) <= 120)   -- private: visitors can write it, never read it
);

alter table public.notes enable row level security;

drop policy if exists "Anyone can read notes" on public.notes;
create policy "Anyone can read notes" on public.notes
  for select to anon using (true);

drop policy if exists "Anyone can add a note" on public.notes;
create policy "Anyone can add a note" on public.notes
  for insert to anon with check (true);

-- column-level access: the public can read every column EXCEPT email,
-- and can only fill in these four columns (not id or created_at)
revoke all on public.notes from anon;
grant select (id, created_at, body, name, color) on public.notes to anon;
grant insert (body, name, color, email) on public.notes to anon;

-- ── VISITOR COUNTER (each browser counts once) ─────────────
create table if not exists public.visitors (
  visitor_id  uuid primary key,
  first_seen  timestamptz not null default now(),
  n           bigint generated always as identity
);

alter table public.visitors enable row level security;   -- no policies: not readable by the public
revoke all on public.visitors from anon;

-- registers a visitor (once) and returns their place in line: 1, 2, 3, …
create or replace function public.register_visit(vid uuid)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  my_n bigint;
begin
  insert into visitors (visitor_id) values (vid) on conflict (visitor_id) do nothing;
  select n into my_n from visitors where visitor_id = vid;
  return (select count(*) from visitors where n <= my_n);
end;
$$;

revoke all on function public.register_visit(uuid) from public;
grant execute on function public.register_visit(uuid) to anon;

